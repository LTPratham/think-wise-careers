"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { zodResolver } from "@hookform/resolvers/zod";
import { useForm } from "react-hook-form";
import * as z from "zod";
import { Button } from "@/components/ui/button";
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from "@/components/ui/form";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { toast } from "@/components/ui/toast";
import { Save, Trash2, Upload, Building2, X, AlertTriangle, Loader2, Sparkles } from "lucide-react";

const universitySchema = z.object({
  name: z.string().min(2, "University name is required"),
  countryName: z.string().min(2, "Country name is required"),
  logoUrl: z.string().optional().nullable(),
  description: z.string().min(10, "Description is required"),
});

type UniversityValues = z.infer<typeof universitySchema>;

export function UniversityForm({ initialData }: { initialData?: any }) {
  const router = useRouter();

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isDeleting, setIsDeleting] = useState(false);
  const [showDeleteConfirm, setShowDeleteConfirm] = useState(false);
  const [isUploadingLogo, setIsUploadingLogo] = useState(false);

  const form = useForm<UniversityValues>({
    resolver: zodResolver(universitySchema) as any,
    defaultValues: {
      name: initialData?.name || "",
      countryName: initialData?.countryName || "",
      logoUrl: initialData?.logoUrl || "",
      description: initialData?.description || "",
    },
  });

  // Client-side image compression to optimize speed & guarantee serverless compatibility
  const compressImage = (file: File, maxWidth = 500, maxHeight = 500, quality = 0.88): Promise<string> => {
    return new Promise((resolve) => {
      if (file.type === "image/svg+xml") {
        const reader = new FileReader();
        reader.onload = (ev) => resolve(ev.target?.result as string);
        reader.onerror = () => resolve("");
        reader.readAsDataURL(file);
        return;
      }

      const reader = new FileReader();
      reader.onload = (e) => {
        const img = new Image();
        img.onload = () => {
          const canvas = document.createElement("canvas");
          let { width, height } = img;

          if (width > maxWidth || height > maxHeight) {
            const ratio = Math.min(maxWidth / width, maxHeight / height);
            width = Math.round(width * ratio);
            height = Math.round(height * ratio);
          }

          canvas.width = width;
          canvas.height = height;
          const ctx = canvas.getContext("2d");
          if (!ctx) {
            resolve(e.target?.result as string);
            return;
          }

          ctx.drawImage(img, 0, 0, width, height);
          resolve(canvas.toDataURL("image/jpeg", quality));
        };
        img.onerror = () => resolve(e.target?.result as string);
        img.src = e.target?.result as string;
      };
      reader.onerror = () => resolve("");
      reader.readAsDataURL(file);
    });
  };

  // Handle Logo Upload
  const handleLogoUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    setIsUploadingLogo(true);
    try {
      // 1. Generate client-compressed image first as guaranteed instant fallback
      const fallbackDataUrl = await compressImage(file, 500, 500);

      // 2. Attempt server upload
      const formData = new FormData();
      formData.append("file", file);
      formData.append("type", "university");

      try {
        const res = await fetch("/api/admin/upload", {
          method: "POST",
          body: formData,
        });

        if (res.ok) {
          const data = await res.json();
          form.setValue("logoUrl", data.url, { shouldDirty: true });
          toast({ title: "Logo uploaded successfully!" });
          return;
        }
      } catch (networkErr) {
        console.warn("Server upload failed, using local fallback", networkErr);
      }

      if (fallbackDataUrl) {
        form.setValue("logoUrl", fallbackDataUrl, { shouldDirty: true });
        toast({ title: "Logo attached successfully!" });
      } else {
        throw new Error("Could not process selected logo file.");
      }
    } catch (err: any) {
      toast({ title: err.message || "Failed to upload logo", variant: "destructive" });
    } finally {
      setIsUploadingLogo(false);
      e.target.value = "";
    }
  };

  const handleAutoGenerateDescription = () => {
    const uniName = form.getValues("name")?.trim();
    const country = form.getValues("countryName")?.trim();
    if (!uniName) {
      toast({ title: "Please enter the university name first!", variant: "destructive" });
      return;
    }
    const locationPart = country ? ` in ${country}` : "";
    form.setValue(
      "description",
      `${uniName} is an internationally recognized higher education institution${locationPart}, distinguished for its academic excellence, vibrant campus community, world-class faculty, and outstanding career outcomes for global students.`,
      { shouldDirty: true }
    );
    toast({ title: "Generated university description!" });
  };

  const onSubmit = async (data: UniversityValues) => {
    setIsSubmitting(true);
    try {
      const url = initialData ? `/api/admin/universities/${initialData.id}` : `/api/admin/universities`;
      const method = initialData ? "PUT" : "POST";

      const res = await fetch(url, {
        method,
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(data),
      });

      if (!res.ok) {
        const err = await res.json().catch(() => ({}));
        throw new Error(err.error || "Failed to save university");
      }

      toast({ title: initialData ? "University updated successfully!" : "University created successfully!" });
      router.push("/admin/universities");
      router.refresh();
    } catch (error: any) {
      toast({ title: error.message || "Error saving university", variant: "destructive" });
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleDelete = async () => {
    if (!initialData?.id) return;
    setIsDeleting(true);
    try {
      const res = await fetch(`/api/admin/universities/${initialData.id}`, {
        method: "DELETE",
      });

      if (!res.ok) {
        const err = await res.json().catch(() => ({}));
        throw new Error(err.error || "Failed to delete university");
      }

      toast({ title: "University deleted successfully!" });
      router.push("/admin/universities");
      router.refresh();
    } catch (err: any) {
      toast({ title: err.message || "Error deleting university", variant: "destructive" });
    } finally {
      setIsDeleting(false);
      setShowDeleteConfirm(false);
    }
  };

  const currentLogoUrl = form.watch("logoUrl");

  return (
    <>
      <Form {...form}>
        <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-6">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            <FormField
              control={form.control}
              name="name"
              render={({ field }) => (
                <FormItem>
                  <FormLabel className="font-semibold text-slate-700">University Name</FormLabel>
                  <FormControl>
                    <Input placeholder="e.g. University of Manchester" {...field} />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <FormField
              control={form.control}
              name="countryName"
              render={({ field }) => (
                <FormItem>
                  <FormLabel className="font-semibold text-slate-700">Country</FormLabel>
                  <FormControl>
                    <Input placeholder="e.g. United Kingdom" {...field} />
                  </FormControl>
                  <div className="flex flex-wrap items-center gap-1.5 pt-1">
                    <span className="text-2xs text-slate-400 font-medium">Quick Pick:</span>
                    {[
                      "United Kingdom",
                      "United States",
                      "Canada",
                      "Australia",
                      "Germany",
                      "Ireland",
                      "France",
                      "New Zealand",
                      "Dubai",
                      "Singapore",
                    ].map((c) => (
                      <button
                        key={c}
                        type="button"
                        onClick={() => form.setValue("countryName", c, { shouldDirty: true })}
                        className="text-2xs px-2 py-0.5 rounded-md bg-slate-100 hover:bg-indigo-50 text-slate-600 hover:text-indigo-600 border border-slate-200 transition-colors"
                      >
                        {c}
                      </button>
                    ))}
                  </div>
                  <FormMessage />
                </FormItem>
              )}
            />
          </div>

          {/* Logo Upload Section */}
          <div className="bg-slate-50 p-6 rounded-xl border border-slate-200 space-y-4">
            <label className="block text-sm font-semibold text-slate-700">University Logo</label>

            <div className="flex items-center space-x-6">
              {/* Logo Preview */}
              <div className="w-20 h-20 rounded-xl bg-white border border-slate-200 p-2 relative flex items-center justify-center shrink-0">
                {currentLogoUrl ? (
                  <>
                    <img
                      src={currentLogoUrl}
                      alt="Logo Preview"
                      className="w-full h-full object-contain"
                    />
                    <button
                      type="button"
                      onClick={() => form.setValue("logoUrl", "", { shouldDirty: true })}
                      className="absolute -top-2 -right-2 p-1 bg-red-600 text-white rounded-full hover:bg-red-700 shadow-md"
                      title="Remove logo"
                    >
                      <X className="w-3 h-3" />
                    </button>
                  </>
                ) : (
                  <Building2 className="w-8 h-8 text-slate-300" />
                )}
              </div>

              {/* Upload Controls */}
              <div className="space-y-2 flex-1">
                <label className="cursor-pointer inline-block">
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    disabled={isUploadingLogo}
                    asChild
                  >
                    <span>
                      {isUploadingLogo ? (
                        <>
                          <Loader2 className="w-4 h-4 mr-2 animate-spin" /> Uploading...
                        </>
                      ) : (
                        <>
                          <Upload className="w-4 h-4 mr-2" /> Upload Logo Image
                        </>
                      )}
                    </span>
                  </Button>
                  <input
                    type="file"
                    accept="image/png, image/jpeg, image/webp, image/svg+xml"
                    className="hidden"
                    onChange={handleLogoUpload}
                    disabled={isUploadingLogo}
                  />
                </label>
                <p className="text-2xs text-slate-500">
                  Square or horizontal transparent PNG/SVG recommended. Max 5MB.
                </p>

                <FormField
                  control={form.control}
                  name="logoUrl"
                  render={({ field }) => (
                    <FormItem>
                      <FormControl>
                        <Input
                          placeholder="Or paste direct logo URL (https://...)"
                          className="text-xs bg-white"
                          {...field}
                          value={field.value || ""}
                        />
                      </FormControl>
                      <FormMessage />
                    </FormItem>
                  )}
                />
              </div>
            </div>
          </div>

          <FormField
            control={form.control}
            name="description"
            render={({ field }) => (
              <FormItem>
                <div className="flex items-center justify-between">
                  <FormLabel className="font-semibold text-slate-700">Description</FormLabel>
                  <button
                    type="button"
                    onClick={handleAutoGenerateDescription}
                    className="text-xs text-indigo-600 hover:text-indigo-800 font-semibold flex items-center bg-indigo-50/80 hover:bg-indigo-100 px-2.5 py-1 rounded-md border border-indigo-200 transition-colors shadow-2xs"
                  >
                    <Sparkles className="w-3.5 h-3.5 mr-1.5 text-indigo-600" />
                    Auto-Generate Description
                  </button>
                </div>
                <FormControl>
                  <Textarea
                    placeholder="Brief overview of the university, rankings, key faculties, campus highlights..."
                    className="h-32 text-sm"
                    {...field}
                    value={field.value || ""}
                  />
                </FormControl>
                <FormMessage />
              </FormItem>
            )}
          />

          <div className="pt-4 border-t flex flex-wrap items-center justify-between gap-4">
            <div>
              {initialData && (
                <Button
                  type="button"
                  variant="outline"
                  onClick={() => setShowDeleteConfirm(true)}
                  className="text-red-600 hover:text-red-700 hover:bg-red-50 border-red-200"
                >
                  <Trash2 className="w-4 h-4 mr-2" /> Delete University
                </Button>
              )}
            </div>

            <div className="flex items-center space-x-3">
              <Button
                type="button"
                variant="outline"
                onClick={() => router.push("/admin/universities")}
              >
                Cancel
              </Button>
              <Button type="submit" disabled={isSubmitting}>
                {isSubmitting ? (
                  <>
                    <Loader2 className="w-4 h-4 mr-2 animate-spin" /> Saving...
                  </>
                ) : (
                  <>
                    <Save className="w-4 h-4 mr-2" /> Save University
                  </>
                )}
              </Button>
            </div>
          </div>
        </form>
      </Form>

      {/* Delete Confirmation Modal */}
      {showDeleteConfirm && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/50 backdrop-blur-xs p-4">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-2xl border border-slate-200 animate-in fade-in zoom-in-95 duration-150">
            <div className="w-12 h-12 rounded-full bg-red-100 text-red-600 flex items-center justify-center mb-4">
              <AlertTriangle className="w-6 h-6" />
            </div>

            <h3 className="text-xl font-bold font-outfit text-slate-900 mb-2">
              Delete {initialData?.name}?
            </h3>
            <p className="text-sm text-slate-600 leading-relaxed mb-6">
              Are you sure you want to delete this university? It will be removed from all linked country pages.
            </p>

            <div className="flex items-center justify-end space-x-3">
              <Button
                variant="outline"
                onClick={() => setShowDeleteConfirm(false)}
                disabled={isDeleting}
              >
                Cancel
              </Button>
              <Button
                variant="destructive"
                onClick={handleDelete}
                disabled={isDeleting}
                className="bg-red-600 hover:bg-red-700"
              >
                {isDeleting ? (
                  <>
                    <Loader2 className="w-4 h-4 mr-2 animate-spin" /> Deleting...
                  </>
                ) : (
                  <>
                    <Trash2 className="w-4 h-4 mr-2" /> Yes, Delete
                  </>
                )}
              </Button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
